/// A section title inside a screen.
/// Where the share sheet points from. iPad needs it (the sheet is a popover);
/// without it sharing fails there. Pass the tapped widget's context if you
/// have it; otherwise the middle of the screen is used.
Rect apawShareOrigin(BuildContext context) {
  final box = context.findRenderObject();
  if (box is RenderBox && box.hasSize && box.attached) {
    return box.localToGlobal(Offset.zero) & box.size;
  }
  final s = MediaQuery.maybeOf(context)?.size ?? const Size(400, 800);
  return Rect.fromCenter(center: Offset(s.width / 2, s.height / 2), width: 1, height: 1);
}


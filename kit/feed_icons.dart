/// Every a-Paw app's front door, laid out like Spot a Paw's: the app's logo,
/// its promise, what it does (icons), the meals line, then create / sign in.
/// Sign in, create account, forgot password and "Check your email" talk to
/// Supabase directly; FlutterFlow's auth state follows the session.
class ApawFrontDoor extends StatefulWidget {
  const ApawFrontDoor({
    super.key,
    required this.app,
    required this.name,
    required this.promise,

      'target_type': targetType,
      'target_id': targetId,
      'reason': reason,
      'details': note.text.trim().isEmpty ? null : note.text.trim(),
    });
    msg = 'Thank you. We will look at it.';
  } on PostgrestException catch (e) {
    msg = e.code == '23505' ? 'You have already reported this portrait.' : 'Could not send the report. Try again.';
  } catch (_) {
    msg = 'Could not send the report. Try again.';
  }
  // A dialog, not a snackbar: the thank-you was gone before people (and the
  // Test Pilot run, 7 Oct) saw it, so they sent the report twice.
  if (context.mounted) {
    await showDialog<void>(
      context: context,
      builder: (d) => apawThemed(AlertDialog(
        backgroundColor: ApawColors.cream,
        icon: apawIconChip(msg.startsWith('Thank') ? 'common-done' : 'common-report-other', size: 48),
        title: Text(msg.startsWith('Thank') ? 'Report sent' : 'Report', style: apawDisplay(size: 22)),
        content: Text(msg, style: apawText(size: 15, color: ApawColors.ink)),
        actions: [TextButton(onPressed: () => Navigator.pop(d), child: const Text('OK'))],
      )),
    );
  }
}


/// An icon on a soft rounded square.
Widget apawIconChip(String icon, {double size = 44, Color bg = ApawColors.peach, Color color = ApawColors.orange}) {
  Widget plain() => Container(
        width: size,
        height: size,
        decoration: BoxDecoration(color: bg, borderRadius: BorderRadius.circular(size * .3)),
        alignment: Alignment.center,
        child: apawIcon(icon, color: color, size: size * .52),
      );
  // Only the default tile becomes a regional badge; coloured ones (lost,
  // found, warnings) keep their meaning. Badges want 48px or more.
  if (bg != ApawColors.peach || color != ApawColors.orange || size < 36) return plain();
  return ValueListenableBuilder<String>(
    valueListenable: ApawSkin.current,
    builder: (_, skin, __) {
      if (skin == 'standard') return plain();
      final big = size < 48 ? 48.0 : size;
      return SizedBox(
        width: big,
        height: big,
        child: SvgPicture.network(ApawSkin.art(skin, 'badges', icon),
            width: big, height: big, excludeFromSemantics: true, placeholderBuilder: (_) => Center(child: plain())),
      );
    },
  );
}


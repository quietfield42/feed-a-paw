/// A pack icon, tinted [color]. Unknown names draw nothing (never crash).
Widget apawIcon(String name, {double size = 24, Color color = ApawColors.ink}) {
  final svg = _apawUi[name];
  if (svg == null) return SizedBox(width: size, height: size);
  return SvgPicture.string(svg,
      width: size, height: size, colorFilter: ColorFilter.mode(color, BlendMode.srcIn), excludeFromSemantics: true);
}

/// An empty-state picture (240 x 160 artwork) at [width].
Widget apawEmpty(String name, {double width = 200}) {
  Widget plain() {
    final svg = _apawEmpty[name];
    if (svg == null) return SizedBox(width: width, height: width * 2 / 3);
    return SvgPicture.string(svg, width: width, height: width * 2 / 3, excludeFromSemantics: true);

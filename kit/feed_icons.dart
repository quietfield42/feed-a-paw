/// "Look & feel": the same seven skins as Spot a Paw. A skin changes the
/// scenery behind the pages, never the buttons, icons or text colours. The
/// choice is saved on the phone and on the a-Paw account (profiles.skin), so
/// it follows the person into every a-Paw app.
class ApawSkin {
  // Spot a Paw's skin art (same folders and names as Spot uses).
  static const base = 'https://qyyydmjrrtyauyawheos.supabase.co/storage/v1/object/public/'
      'report-media/ea87c808-aa49-4286-829b-e69250be5b84/icons';
  static const skins = <(String, String, String)>[
    ('standard', 'No Frills', 'Flat and plain, easy on the eyes'),
    ('eg', 'Egyptian', 'Papyrus scrolls, Nile scenes'),
    ('south-asia', 'South Asia', 'Fibre paper, rivers and rice fields'),
    ('southeast-asia', 'Southeast Asia', 'Mulberry paper, bamboo and terraces'),
    ('west-asia', 'West Asia', 'Parchment, palms and stone courtyards'),
    ('south-america', 'South America', 'Woven paper, rivers and highlands'),
    ('africa', 'Africa', 'Earth pigments, savannah light and woven cloth'),
  ];
  /// The family's default look: Egyptian (Ash, 7 Oct 2026). No Frills is a choice like any other.
  static const fallback = 'eg';
  static final current = ValueNotifier<String>(fallback);
  static bool _loaded = false;

  static String label(String key) =>
      skins.firstWhere((s) => s.$1 == key, orElse: () => skins.first).$2;

  // Only scenes light enough for dark text in every region (measured
  // 30 Sep: profile, auth, dusk, spot and communities are too dark in some).
  static const _lightScenes = {'paws', 'onboarding', 'rescues'};
  static String bg(String skin, String scene) =>
      '$base/$skin/bg_${_lightScenes.contains(scene) ? scene : 'paws'}.jpg';

  /// The a-Paw regional pack (a-paw-seven-skins, Crafted Pixel), published
  /// with the web previews: badges, empty states and app logos per region.
  static const packBase = 'https://spotapaw.github.io/a-paw-apps/skins';
  static String folder(String skin) => skin == 'eg' ? 'egyptian' : skin;

  /// A regional file for a pack name like 'care-health-vaccination'
  /// (kind: 'badges' or 'empty-states'; the app folder is the name's prefix).
  static String art(String skin, String kind, String name) =>
      '$packBase/${folder(skin)}/$kind/${name.split('-').first}/$name.svg';

  /// Each region's paper colour (theme.json), used lightly on cards.
  static const paper = <String, Color>{
    'eg': Color(0xFFF3E5BC),
    'south-asia': Color(0xFFF2DDD0),
    'southeast-asia': Color(0xFFE3EAD3),
    'west-asia': Color(0xFFF0DEC8),
    'south-america': Color(0xFFECE8D6),
    'africa': Color(0xFFEAD6B5),
  };

  static String _norm(String s) => s == 'egypt' || s == 'egyptian' ? 'eg' : s;

  /// Phone first (instant), then the account (follows the person).
  static Future<void> load() async {
    if (_loaded) return;
    _loaded = true;
    var chosenHere = false;
    try {
      final prefs = await SharedPreferences.getInstance();
      final s = prefs.getString('apaw_skin');
      if (s != null && s.isNotEmpty) {
        current.value = _norm(s);
        chosenHere = true;
      }
    } catch (_) {}
    try {
      final uid = SupaFlow.client.auth.currentUser?.id;
      if (uid == null) return;
      final r = await SupaFlow.client.from('profiles').select('skin').eq('id', uid).maybeSingle();
      final s = _norm((r?['skin'] ?? '').toString());
      if (s == fallback && chosenHere && current.value != fallback) {
        // Picked on this phone before the account could store it: keep it.
        await SupaFlow.client.from('profiles').update({'skin': current.value}).eq('id', uid);
      } else if (s.isNotEmpty && skins.any((k) => k.$1 == s) && s != current.value) {
        current.value = s;
        (await SharedPreferences.getInstance()).setString('apaw_skin', s);
      }
    } catch (_) {}
  }

  static Future<void> set(String s) async {
    current.value = s;
    try {
      (await SharedPreferences.getInstance()).setString('apaw_skin', s);
    } catch (_) {}
    try {
      final uid = SupaFlow.client.auth.currentUser?.id;
      if (uid != null) await SupaFlow.client.from('profiles').update({'skin': s}).eq('id', uid);
    } catch (_) {}
  }
}


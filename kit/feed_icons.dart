enum _ApawDoor { welcome, signIn, create, forgot }

const _apawConfirmedUrl = 'https://spotapaw.github.io/care-a-paw-site/confirmed/';

/// Every a-Paw app's front door, laid out like Spot a Paw's: the app's logo,
/// its promise, what it does (icons), the meals line, then create / sign in.
/// Sign in, create account, forgot password and "Check your email" talk to
/// Supabase directly; FlutterFlow's auth state follows the session.
class ApawFrontDoor extends StatefulWidget {
  const ApawFrontDoor({
    super.key,
    required this.app,
    required this.name,
    required this.promise,
    required this.blurb,
    required this.features,
    required this.meals,
    required this.homeRoute,
    this.guestLabel,
    this.guestRoute,
    this.width,
    this.height,
  });

  final String app;
  final String name;
  final String promise;
  final String blurb;
  final List<ApawFeature> features;
  final String meals;
  final String homeRoute;

  /// Optional "look around first" link for apps that are open to everyone
  /// (Feed-a-Paw): the label and the route it goes to without an account.
  final String? guestLabel;
  final String? guestRoute;
  final double? width;
  final double? height;

  @override
  State<ApawFrontDoor> createState() => _ApawFrontDoorState();
}

class _ApawFrontDoorState extends State<ApawFrontDoor> {
  _ApawDoor _mode = _ApawDoor.welcome;
  final _email = TextEditingController();
  final _password = TextEditingController();
  bool _busy = false;
  bool _hide = true;
  String _error = '';

  @override
  void dispose() {
    _email.dispose();
    _password.dispose();
    super.dispose();
  }

  void _go(_ApawDoor m) => setState(() {
        _mode = m;
        _error = '';
      });

  Future<void> _home() async {
    if (!mounted) return;
    GoRouter.of(context).prepareAuthEvent();
    context.goNamedAuth(widget.homeRoute, context.mounted);
  }

  bool _valid() {
    final e = _email.text.trim();
    if (!e.contains('@') || e.length < 5) {
      setState(() => _error = 'Enter your email address.');
      return false;
    }
    if (_mode != _ApawDoor.forgot && _password.text.length < 8) {
      setState(() => _error = 'Passwords are at least 8 characters.');
      return false;
    }
    return true;
  }

  Future<void> _signIn() async {
    if (!_valid()) return;
    setState(() {
      _busy = true;
      _error = '';
    });
    try {
      final res = await SupaFlow.client.auth.signInWithPassword(email: _email.text.trim(), password: _password.text);
      if (res.session != null) {
        await _home();
        return;
      }
    } on AuthException catch (e) {
      final m = '${e.code ?? ''} ${e.message}'.toLowerCase();
      if (m.contains('not confirmed') || m.contains('not_confirmed')) {
        setState(() => _busy = false);
        if (await _checkEmail()) await _home();
        return;
      }
      setState(() => _error = m.contains('invalid') ? 'That email and password don’t match.' : e.message);
    } catch (_) {
      setState(() => _error = 'Could not sign in. Check your signal and try again.');
    }
    if (mounted) setState(() => _busy = false);
  }

  Future<void> _create() async {
    if (!_valid()) return;
    setState(() {
      _busy = true;
      _error = '';
    });
    try {
      final res = await SupaFlow.client.auth
          .signUp(email: _email.text.trim(), password: _password.text, emailRedirectTo: _apawConfirmedUrl);
      if (res.session != null) {
        await _home();
        return;
      }
      setState(() => _busy = false);
      if (await _checkEmail()) await _home();
      return;
    } on AuthException catch (e) {
      final m = e.message.toLowerCase();
      setState(() => _error = m.contains('already') ? 'That email already has an account. Sign in instead.' : e.message);
    } catch (_) {
      setState(() => _error = 'Could not create your account. Please try again.');
    }
    if (mounted) setState(() => _busy = false);
  }

  Future<void> _forgot() async {
    if (!_valid()) return;
    setState(() {
      _busy = true;
      _error = '';
    });
    try {
      await SupaFlow.client.auth.resetPasswordForEmail(_email.text.trim());
    } catch (_) {}
    if (!mounted) return;
    setState(() => _busy = false);
    ScaffoldMessenger.of(context).showSnackBar(const SnackBar(
        content: Text('If that email has an account, a reset link is on its way.'), duration: Duration(seconds: 5)));
    _go(_ApawDoor.signIn);
  }

  Future<bool> _checkEmail() async {
    final address = _email.text.trim();
    final secret = _password.text;
    var note = '';
    var busy = false;
    StreamSubscription<AuthState>? watch;
    final ok = await showModalBottomSheet<bool>(
      context: context,
      isScrollControlled: true,
      isDismissible: false,
      enableDrag: false,
      builder: (sheet) {
        watch ??= SupaFlow.client.auth.onAuthStateChange.listen((s) {
          if (s.session != null && Navigator.of(sheet).canPop()) Navigator.of(sheet).pop(true);
        });
        return apawThemed(StatefulBuilder(
          builder: (sheet, redraw) => SafeArea(
            top: false,
            child: Padding(
              padding: const EdgeInsets.fromLTRB(22, 4, 22, 16),
              child: Column(mainAxisSize: MainAxisSize.min, crossAxisAlignment: CrossAxisAlignment.stretch, children: [
                Center(child: apawIconChip('common-send', size: 64)),
                const SizedBox(height: 14),
                Text('Check your email', textAlign: TextAlign.center, style: apawDisplay(size: 26)),
                const SizedBox(height: 6),
                Text('We sent a link to $address. Tap it to confirm your account, then come back here.',
                    textAlign: TextAlign.center, style: apawText(color: ApawColors.muted)),
                const SizedBox(height: 4),
                Text('Not there? Look in Junk or Spam.',
                    textAlign: TextAlign.center, style: apawText(size: 13, color: ApawColors.muted)),
                if (note.isNotEmpty) ...[
                  const SizedBox(height: 12),
                  Text(note, textAlign: TextAlign.center, style: apawText(color: ApawColors.forest, weight: FontWeight.w700)),
                ],
                const SizedBox(height: 18),
                apawPrimary('I’ve confirmed it', () async {
                  redraw(() => busy = true);
                  try {
                    final r = await SupaFlow.client.auth.signInWithPassword(email: address, password: secret);
                    if (r.session != null && Navigator.of(sheet).canPop()) {
                      Navigator.of(sheet).pop(true);
                      return;
                    }
                  } on AuthException catch (e) {
                    final m = '${e.code ?? ''} ${e.message}'.toLowerCase();
                    redraw(() => note = m.contains('not confirmed') || m.contains('not_confirmed')
                        ? 'Not confirmed yet. Tap the link in the email first.'
                        : e.message);
                  } catch (_) {
                    redraw(() => note = 'Could not check. Try again.');
                  }
                  redraw(() => busy = false);
                }, busy: busy),
                const SizedBox(height: 10),
                apawSecondary('Send it again', busy
                    ? null
                    : () async {
                        redraw(() => busy = true);
                        try {
                          await SupaFlow.client.auth.resend(type: OtpType.signup, email: address, emailRedirectTo: _apawConfirmedUrl);
                          redraw(() => note = 'Sent again. It can take a minute.');
                        } catch (_) {
                          redraw(() => note = 'Just sent one. Wait a minute and try again.');
                        }
                        redraw(() => busy = false);
                      }),
                TextButton(onPressed: () => Navigator.of(sheet).pop(false), child: const Text('Use a different email')),
              ]),
            ),
          ),
        ));
      },
    );
    await watch?.cancel();
    return ok == true || SupaFlow.client.auth.currentSession != null;
  }

  Widget _link(String label, VoidCallback onTap) =>
      TextButton(onPressed: _busy ? null : onTap, child: Text(label));

  Widget _welcome() => Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
        const SizedBox(height: 8),
        Center(
          child: Container(
            decoration: BoxDecoration(borderRadius: BorderRadius.circular(34), boxShadow: const [
              BoxShadow(color: Color(0x331F5148), blurRadius: 24, offset: Offset(0, 10)),
            ]),
            child: apawLogo(widget.app, size: 116),
          ),
        ),
        const SizedBox(height: 18),
        Text(widget.name, textAlign: TextAlign.center, style: apawDisplay(size: 34)),
        const SizedBox(height: 8),
        Text(widget.promise,
            textAlign: TextAlign.center, style: apawText(size: 18, color: ApawColors.ink, weight: FontWeight.w700, height: 1.3)),
        const SizedBox(height: 6),
        Text(widget.blurb, textAlign: TextAlign.center, style: apawText(size: 15, color: ApawColors.muted)),
        const SizedBox(height: 20),
        apawCard(
          color: const Color(0xEEFFFCF7),
          padding: const EdgeInsets.fromLTRB(16, 10, 16, 10),
          child: Column(children: [for (final f in widget.features) apawFeature(f.icon, f.title, f.body)]),
        ),
        const SizedBox(height: 12),
        apawMeals(widget.meals),
        const SizedBox(height: 22),
        apawPrimary('Create an account', () => _go(_ApawDoor.create)),
        const SizedBox(height: 6),
        _link('I already have an account', () => _go(_ApawDoor.signIn)),
        if (widget.guestLabel != null && widget.guestRoute != null)
          _link(widget.guestLabel!, () => context.goNamed(widget.guestRoute!)),
        const SizedBox(height: 2),
        Text('One a-Paw account works in all our apps.',
            textAlign: TextAlign.center, style: apawText(size: 12.5, color: ApawColors.muted)),
      ]);

  Widget _form() {
    final title = switch (_mode) {
      _ApawDoor.signIn => 'Welcome back',
      _ApawDoor.create => 'Create your account',
      _ApawDoor.forgot => 'Reset your password',
      _ApawDoor.welcome => '',
    };
    final line = switch (_mode) {
      _ApawDoor.signIn => 'Sign in with your a-Paw account.',
      _ApawDoor.create => 'One account for every a-Paw app.',
      _ApawDoor.forgot => 'We’ll email you a link to set a new one.',
      _ApawDoor.welcome => '',
    };
    return Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
      Align(
        alignment: Alignment.centerLeft,
        child: IconButton(
          tooltip: 'Back',
          onPressed: () => _go(_ApawDoor.welcome),
          icon: const Icon(Icons.arrow_back_rounded, color: ApawColors.forest),
        ),
      ),
      Center(child: apawLogo(widget.app, size: 76)),
      const SizedBox(height: 16),
      Text(title, textAlign: TextAlign.center, style: apawDisplay(size: 30)),
      const SizedBox(height: 4),
      Text(line, textAlign: TextAlign.center, style: apawText(color: ApawColors.muted)),
      const SizedBox(height: 24),
      TextField(
        controller: _email,
        keyboardType: TextInputType.emailAddress,
        autofillHints: const [AutofillHints.email],
        style: apawText(size: 16),
        decoration: const InputDecoration(labelText: 'Email'),
      ),
      if (_mode != _ApawDoor.forgot) ...[
        const SizedBox(height: 12),
        TextField(
          controller: _password,
          obscureText: _hide,
          autofillHints: [_mode == _ApawDoor.create ? AutofillHints.newPassword : AutofillHints.password],
          style: apawText(size: 16),
          decoration: InputDecoration(
            labelText: _mode == _ApawDoor.create ? 'Password (at least 8 characters)' : 'Password',
            suffixIcon: IconButton(
              tooltip: _hide ? 'Show password' : 'Hide password',
              icon: Icon(_hide ? Icons.visibility_outlined : Icons.visibility_off_outlined, color: ApawColors.muted),
              onPressed: () => setState(() => _hide = !_hide),
            ),
          ),
        ),
      ],
      if (_error.isNotEmpty) ...[
        const SizedBox(height: 12),
        Row(children: [
          apawIcon('common-warning', color: ApawColors.lost, size: 18),
          const SizedBox(width: 8),
          Expanded(child: Text(_error, style: apawText(size: 14, color: ApawColors.lost, weight: FontWeight.w600))),
        ]),
      ],
      const SizedBox(height: 20),
      if (_mode == _ApawDoor.signIn) apawPrimary('Sign in', _signIn, busy: _busy),
      if (_mode == _ApawDoor.create) apawPrimary('Create account', _create, busy: _busy),
      if (_mode == _ApawDoor.forgot) apawPrimary('Send reset link', _forgot, busy: _busy),
      const SizedBox(height: 8),
      if (_mode == _ApawDoor.signIn) _link('Forgot your password?', () => _go(_ApawDoor.forgot)),
      if (_mode == _ApawDoor.signIn) _link('New here? Create an account', () => _go(_ApawDoor.create)),
      if (_mode == _ApawDoor.create) _link('I already have an account', () => _go(_ApawDoor.signIn)),
      if (_mode == _ApawDoor.forgot) _link('Back to sign in', () => _go(_ApawDoor.signIn)),
    ]);
  }


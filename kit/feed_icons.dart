class _ApawFrontDoorState extends State<ApawFrontDoor> {
  _ApawDoor _mode = _ApawDoor.welcome;
  final _email = TextEditingController();
  final _password = TextEditingController();
  bool _busy = false;
  bool _hide = true;
  String _error = '';

  @override
  void dispose() {
    _email.dispose();
    _password.dispose();
    super.dispose();
  }

  void _go(_ApawDoor m) => setState(() {
        _mode = m;
        _error = '';
      });

  Future<void> _home() async {
    if (!mounted) return;
    GoRouter.of(context).prepareAuthEvent();
    context.goNamedAuth(widget.homeRoute, context.mounted);
  }

  bool _valid() {
    final e = _email.text.trim();
    if (!e.contains('@') || e.length < 5) {
      setState(() => _error = 'Enter your email address.');
      return false;
    }
    if (_mode != _ApawDoor.forgot && _password.text.length < 8) {
      setState(() => _error = 'Passwords are at least 8 characters.');
      return false;
    }
    return true;
  }

  Future<void> _signIn() async {
    if (!_valid()) return;
    setState(() {
      _busy = true;
      _error = '';
    });
    try {
      final res = await SupaFlow.client.auth.signInWithPassword(email: _email.text.trim(), password: _password.text);
      if (res.session != null) {
        await _home();
        return;
      }
    } on AuthException catch (e) {
      final m = '${e.code ?? ''} ${e.message}'.toLowerCase();
      if (m.contains('not confirmed') || m.contains('not_confirmed')) {
        setState(() => _busy = false);
        if (await _checkEmail()) await _home();
        return;
      }
      setState(() => _error = m.contains('invalid')
          ? 'That email and password don’t match.'
          : (m.contains('rate') || m.contains('too many') || e.statusCode == '429')
              ? 'Too many tries just now. Wait a minute, then sign in again.'
              : e.message);
    } catch (_) {
      setState(() => _error = 'Could not sign in. Check your signal and try again.');
    }
    if (mounted) setState(() => _busy = false);
  }

  Future<void> _create() async {
    if (!_valid()) return;
    setState(() {
      _busy = true;
      _error = '';
    });
    try {
      final res = await SupaFlow.client.auth
          .signUp(email: _email.text.trim(), password: _password.text, emailRedirectTo: _apawConfirmedUrl);
      if (res.session != null) {
        await _home();
        return;
      }
      // An email that already has an account: Supabase answers "ok" but sends
      // nothing and returns a user with no identities. Say so and go to sign in.
      final ids = res.user?.identities;
      if (ids != null && ids.isEmpty) {
        _busy = false;
        _go(_ApawDoor.signIn);
        setState(() => _error =
            'You already have an a-Paw account with this email. Sign in with your password, or tap Forgot your password.');
        return;
      }
      setState(() => _busy = false);
      if (await _checkEmail()) await _home();
      return;
    } on AuthException catch (e) {
      final m = e.message.toLowerCase();
      setState(() => _error = m.contains('already') ? 'That email already has an account. Sign in instead.' : e.message);
    } catch (_) {
      setState(() => _error = 'Could not create your account. Please try again.');
    }
    if (mounted) setState(() => _busy = false);
  }

  Future<void> _forgot() async {
    if (!_valid()) return;
    setState(() {
      _busy = true;
      _error = '';
    });
    try {
      await SupaFlow.client.auth.resetPasswordForEmail(_email.text.trim());
    } catch (_) {}
    if (!mounted) return;
    setState(() => _busy = false);
    ScaffoldMessenger.of(context).showSnackBar(const SnackBar(
        content: Text('If that email has an account, a reset link is on its way.'), duration: Duration(seconds: 5)));
    _go(_ApawDoor.signIn);
  }

